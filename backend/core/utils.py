def is_valid_stellar_address(address: str) -> bool:
    """
    Validates whether the string is a valid Stellar Public Key (G...).
    """
    if not address or not isinstance(address, str):
        return False
    if not address.startswith('G') or len(address) != 56:
        return False
    try:
        Keypair.from_public_key(address)
        return True
    except (SdkError, Ed25519PublicKeyInvalidError, Exception):
        return False


def verify_stellar_signature(wallet_address: str, message: str, signature_encoded: str) -> bool:
    """
    Verifies an Ed25519 signature generated by a Stellar wallet.
    Accepts signature as hex or base64.
    Supports standard, SEP-0042, and SHA-256 pre-hashed message variants.
    """
    if not is_valid_stellar_address(wallet_address) or not signature_encoded:
        return False
    try:
        import hashlib
        raw_sig = signature_encoded.strip()
        try:
            signature_bytes = bytes.fromhex(raw_sig)
        except ValueError:
            signature_bytes = base64.b64decode(raw_sig)

        keypair = Keypair.from_public_key(wallet_address)
        candidates = [
            message.encode('utf-8'),
            f"stellar.org signed message\n{message}".encode('utf-8'),
            f"stellar.org message signer:\n{message}".encode('utf-8'),
            f"Stellar Signed Message:\n{message}".encode('utf-8'),
        ]

        for cand in candidates:
            try:
                keypair.verify(cand, signature_bytes)
                return True
            except Exception:
                pass

        for cand in candidates:
            try:
                keypair.verify(hashlib.sha256(cand).digest(), signature_bytes)
                return True
            except Exception:
                pass

        return False
    except Exception:
        return False


def sanitize_message(raw_text: str, max_length: int = 280) -> str:
    """
    Sanitizes supporter message to prevent XSS and injection attacks.
    Limits length to prevent UI overflow.
    """
    if not raw_text:
        return ""
    # Strip HTML tags
    clean = re.sub(r'<[^>]*?>', '', str(raw_text))
    # Escape HTML entities
    clean = html.escape(clean)
    # Normalize whitespace
    clean = ' '.join(clean.split())
    return clean[:max_length]


def filter_user_remark(raw_text: str, banned_words: list, action: str = 'mask') -> str:
    """
    Filters or moderates supporter remarks/comments against a creator's banned terms.
    Supported actions:
      - 'mask': replaces matches with asterisks (e.g. '****')
      - 'block': raises ValueError rejecting the tip if prohibited remarks are detected
    """
    if not raw_text or not banned_words:
        return raw_text

    filtered = raw_text
    found_banned = []

    for item in banned_words:
        word = str(item).strip()
        if not word:
            continue
        # Case-insensitive word or phrase matching
        pattern = re.compile(rf'\b{re.escape(word)}\b', re.IGNORECASE)
        if not pattern.search(filtered):
            # Also allow sub-phrase match if contains spaces
            if ' ' in word:
                pattern = re.compile(re.escape(word), re.IGNORECASE)

        if pattern.search(filtered):
            found_banned.append(word)
            if action == 'mask':
                filtered = pattern.sub(lambda m: '*' * len(m.group(0)), filtered)

    if found_banned and action == 'block':
        terms = ', '.join(f'"{t}"' for t in found_banned[:2])
        raise ValueError(f"Your remark contains prohibited term(s) ({terms}) banned by this creator. Please edit your remark.")

    return filtered


def custom_exception_handler(exc, context):
    """
    Consistent JSON error payload across all endpoints.
    """
    response = exception_handler(exc, context)
    if response is not None:
        custom_data = {
            'success': False,
            'status_code': response.status_code,
            'error': {
                'type': exc.__class__.__name__,
                'detail': response.data
            }
        }
        response.data = custom_data
    return response
